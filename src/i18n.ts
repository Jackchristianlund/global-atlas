export type StrKey = keyof typeof S;

export const tr = (key: StrKey, lang: Lang): string => S[key][lang === 'no' ? 0 : 1];

/**
 * A label for a value that comes from a source rather than from this file:
 * UCDP's types of violence, for instance. Where there is no translation the
 * source's own wording is shown, never a blank or the lookup key.
 */
export const trData = (prefix: string, value: string, lang: Lang): string => {
  const row = (S as Record<string, L | undefined>)[`${prefix}${value}`];
  return row ? pick(row, lang) : value;
};
export const pick = (l: L, lang: Lang): string => l[lang === 'no' ? 0 : 1];

export function useT() {
  const lang = useStore((s) => s.lang);
  const t = useCallback((key: StrKey) => tr(key, lang), [lang]);
  const tl = useCallback((l: L) => pick(l, lang), [lang]);
  const td = useCallback((prefix: string, value: string) => trData(prefix, value, lang), [lang]);
  return { t, tl, td, lang };
}

export function fmtDate(isoDate: string, lang: Lang): string {
  if (isoDate.length === 4) return isoDate;
  const d = new Date(isoDate + 'T12:00:00Z');
  if (Number.isNaN(d.getTime())) return isoDate;
  return new Intl.DateTimeFormat(lang === 'no' ? 'nb-NO' : 'en-GB', { day: 'numeric', month: 'short', year: 'numeric', timeZone: 'UTC' }).format(d);
}

export function fmtNum(n: number, lang: Lang, digits = 0): string {
  return new Intl.NumberFormat(lang === 'no' ? 'nb-NO' : 'en-GB', { maximumFractionDigits: digits, minimumFractionDigits: digits }).format(n);
}
