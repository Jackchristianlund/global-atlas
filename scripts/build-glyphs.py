"""
Builds MapLibre glyph ranges for exactly the characters the map draws.

The artifact host serves neither .pbf nor .bin, so the glyphs are inlined into
the bundle as base64 and handed to MapLibre as blob URLs. That makes size the
binding constraint, so the font is subset to the characters that actually occur
in the bundled place names before any range is generated. Full Latin ranges
came to 417 KB; this comes to a fraction of that, and renders identically
because the dropped glyphs were never going to be asked for.
"""
import base64, json, pathlib, subprocess, sys, tempfile
from fontTools import subset

CHARS = pathlib.Path('/tmp/charset.txt').read_text()
FACES = {
    'Noto Sans Regular': '/tmp/fonts/noto-sans/NotoSans-Regular.ttf',
    'Noto Sans Bold': '/tmp/fonts/noto-sans/NotoSans-Bold.ttf',
}
# Ranges MapLibre may ask for, given the characters above.
RANGES = sorted({(cp // 256) * 256 for cp in map(ord, CHARS)})

tmp = pathlib.Path(tempfile.mkdtemp())
out = {}
for name, src in FACES.items():
    opts = subset.Options()
    opts.notdef_outline = True
    opts.layout_features = []
    font = subset.load_font(src, opts)
    sub = subset.Subsetter(options=opts)
    sub.populate(text=CHARS)
    sub.subset(font)
    sub_path = tmp / f'{name}.ttf'
    subset.save_font(font, str(sub_path), opts)
    font.close()
    out[name] = {}
    for start in RANGES:
        end = start + 255
        pbf = subprocess.run(
            [sys.executable and 'node', 'scripts/glyph-range.cjs', str(sub_path), str(start), str(end)],
            capture_output=True, check=True,
        ).stdout
        out[name][f'{start}-{end}'] = base64.b64encode(pbf).decode()

total = sum(len(v) for f in out.values() for v in f.values())
pathlib.Path('src/data/detail').mkdir(parents=True, exist_ok=True)
ts = (
    '// Generated by scripts/build-glyphs.py. Do not edit.\n'
    '// MapLibre glyph ranges, base64, for exactly the characters the bundled\n'
    '// place names use. Inlined because the artifact host serves no binary\n'
    '// glyph file type; see src/map/glyphs.ts for how they are handed over.\n'
    'export const GLYPHS: Record<string, Record<string, string>> = '
    + json.dumps(out, indent=0) + ';\n'
)
pathlib.Path('src/data/detail/glyphs.ts').write_text(ts)
print(f'ranges {RANGES}  base64 {total/1024:.0f} KB')
